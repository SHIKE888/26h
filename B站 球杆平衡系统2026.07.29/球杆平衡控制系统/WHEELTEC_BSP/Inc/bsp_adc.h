#ifndef __BSP_ADC_H
#define __BSP_ADC_H

/* ==========================================================================
 * bsp_adc.h —— 模数转换（ADC）接口
 * --------------------------------------------------------------------------
 * ADC 的作用：把“电压”变成“数字”。
 *   本项目用 12 位 ADC，量程 0~3.3V，读数范围 0~4095。
 *   例如读数 2048 ≈ 1.65V，读数 4095 ≈ 3.3V。
 *
 * 本项目一共用了两个 ADC 外设，各干各的：
 *   ADC1（两个通道，DMA 存二维数组）
 *     - 通道 0 → PB0：电池电压检测（经分压电阻，代码里再乘 11 还原真实电压）
 *     - 通道 1 → PB1：车型选择拨码（老底板功能，球杆系统用不上）
 *   ADC2（一个通道）
 *     - PA1（ADC2_IN1）→ 【角位移传感器】！这是球杆系统的角度反馈来源。
 *
 * 角位移传感器怎么工作？
 *   它本质是一个“旋转电位器”（可以想成一个能转的分压电阻）：
 *   两端接 3.3V 和 GND，中间抽头输出的电压随转角线性变化。
 *   球杆转到不同角度 → 抽头电压不同 → ADC 读数不同。
 *   所以代码里“角度”这个量的单位不是“度”，而是直接用 ADC 计数值(0~4095)。
 * ========================================================================== */

#include <stdint.h>

//ADC存放在缓冲区的索引值（对应 ADC1 的两个通道在数组里的列号）
#define userconfigADC_VOL_CHANNEL       0   //电池电压 → PB0
#define userconfigADC_CARMODE_CHANNEL   1   //车型识别 → PB1

//对外接口
//读 ADC1 某个通道的滑动平均值（channel 传上面两个宏之一）
uint16_t USER_ADC_Get_AdcBufValue(uint8_t channel);
//读 ADC2（PA1，角位移传感器）的平均值，返回 0~4095
uint16_t USER_ADC2_Get_AdcBufValue(void);
//启动 ADC + DMA 循环采样（在 main.c 里上电时调用一次即可）
void ADC_Userconfig_Init(void);


#endif /* __BSP_ADC_H */
